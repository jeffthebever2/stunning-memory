import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {startFreebuff} from './server.js';
import {connectHostedWorkspace} from './hosted.js';
const id=process.env.FREEBUFF_TEST_WORKSPACE;
if(!id)throw Error('FREEBUFF_TEST_WORKSPACE must identify an SDK-created fixture workspace');
const app=await startFreebuff({version:'0.0.201'});
const checks=[];
try {
 const cloud=await connectHostedWorkspace(app.client);
 const activity=await cloud.openWorkspace(id,{signal:AbortSignal.timeout(120000)});
 checks.push('Cloud workspace activity opened');
 const name='sdk-file-'+crypto.randomUUID()+'.txt';
 await cloud.createFile(id,name);
 const initial=await cloud.readFile(id,name);
 console.log(JSON.stringify({activityKeys:Object.keys(activity),fileKeys:Object.keys(initial)}));
 assert.equal(typeof initial.revision,'string');
 const text='SDK_FILES_'+crypto.randomUUID();
 await cloud.saveFile(id,name,text,initial.revision);
 const saved=await cloud.readFile(id,name);
 assert.equal(saved.content,text);
 checks.push('File create/read/revision-checked save and readback');
 await assert.rejects(cloud.saveFile(id,name,'must not overwrite',initial.revision),error=>error.conflict===true||error.status===409);
 assert.equal((await cloud.readFile(id,name)).content,text);
 checks.push('Stale revision conflict preserves saved content');
 const listed=await cloud.listFiles(id);
 assert.ok(listed.some(file=>file.path===name||file.name===name));
 assert.equal(await (await cloud.downloadFile(id,name)).text(),text);
 checks.push('File listing and binary download');
 const binary=new Uint8Array([0,1,2,255]);
 const binaryName='sdk-binary-'+crypto.randomUUID()+'.bin';
 await cloud.uploadFile(id,binaryName,binary);
 assert.deepEqual(new Uint8Array(await(await cloud.downloadFile(id,binaryName)).arrayBuffer()),binary);
 checks.push('Base64 workspace file upload and exact binary download');
 const bytes=new TextEncoder().encode('SDK_STORED_'+crypto.randomUUID());
 const scope={kind:'chat',id};
 const source=await cloud.uploadStoredFile(scope,{name:'sdk-stored.txt',mediaType:'text/plain',data:bytes});
 assert.deepEqual(new Uint8Array(await(await cloud.readStoredFile(scope,source.id)).arrayBuffer()),bytes);
 const stored=await cloud.listStoredFiles(scope);
 assert.ok(stored.some(file=>file.id===source.id));
 checks.push('Stored chat attachment upload/list/download');
 const report={status:'passed',version:'0.0.201',checks};
 await fs.writeFile(new URL('./evidence/files-validation.json',import.meta.url),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
}finally{await app.stop();}
